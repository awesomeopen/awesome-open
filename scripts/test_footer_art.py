def png(width=2048, height=682):
    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data))
    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 6, 0, 0, 0))
            + chunk(b'IDAT', zlib.compress((b'\x00' + b'\x00' * width * 4) * height)) + chunk(b'IEND', b''))


class FooterArtTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.directory = self.root / 'site/footer-backgrounds'
        self.directory.mkdir(parents=True)
        self.name = '000-new & "fixture" #%?.PNG'
        self.asset = self.directory / self.name
        self.asset.write_bytes(png(1200, 400))
        self.manifest = self.directory / 'provenance.json'
        self.manifest.write_text(json.dumps([{'file': self.name, 'width': 1200, 'height': 400,
            'source': 'Synthetic transparent test fixture', 'processing': 'Generated by test only'}]))

    def test_selection_ignores_hidden_nested_and_unsupported_files(self):
        (self.directory / '.hidden.png').write_bytes(b'invalid')
        (self.directory / 'unsafe.svg').write_text('<svg/>')
        (self.directory / 'note.txt').write_text('metadata')
        (self.directory / 'nested').mkdir()
        (self.directory / 'nested/image.png').write_bytes(b'invalid')
        (self.directory / 'directory.png').mkdir()
        (self.root / 'site/patterns').mkdir()
        (self.root / 'site/patterns/pattern.png').write_bytes(b'invalid')
        self.assertEqual(list(discover_footer_art(self.root)), ['footer-backgrounds/' + self.name])

    def test_missing_provenance_and_wrong_dimensions_fail(self):
        self.manifest.write_text('[]')
        with self.assertRaisesRegex(ValueError, 'Missing footer artwork provenance'):
            discover_footer_art(self.root)
        self.setUp()
        self.asset.write_bytes(png(10, 10))
        with self.assertRaisesRegex(ValueError, 'dimensions must match provenance'):
            discover_footer_art(self.root)

    def test_other_resolutions_are_accepted_with_actual_dimensions(self):
        self.asset.write_bytes(png(1200, 400))
        record = json.loads(self.manifest.read_text())
        record[0].update(width=1200, height=400)
        self.manifest.write_text(json.dumps(record))
        self.assertEqual(discover_footer_art(self.root)['footer-backgrounds/' + self.name], (1200, 400))

    def test_symlinks_fail(self):
        (self.directory / 'linked.png').symlink_to(self.asset)
        with self.assertRaisesRegex(ValueError, 'Symlink footer artwork'):
            discover_footer_art(self.root)

    def test_new_file_is_sorted_copied_embedded_and_requires_inventory(self):
        source = self.root / 'source'
        shutil.copytree(ROOT / 'site', source / 'site')
        shutil.copytree(ROOT / 'data', source / 'data')
        shutil.copyfile(ROOT / 'README.source.md', source / 'README.source.md')
        asset = source / 'site/footer-backgrounds' / self.name
        asset.write_bytes(self.asset.read_bytes())
        manifest = source / 'site/footer-backgrounds/provenance.json'
        manifest.write_text(json.dumps(json.loads(self.manifest.read_text()) + json.loads(manifest.read_text())))
        with patch.object(check_brand, 'ROOT', source):
            inventory = check_brand.asset_inventory()
            old = json.loads((ROOT / 'brand/assets.lock.json').read_text())['files']
            errors = check_brand.compare('Asset', old, inventory)
        self.assertIn('Asset: unrecorded site/footer-backgrounds/' + self.name, errors)
        output = self.root / 'output'
        catalog = build(output, root=source, source_sha='a' * 40)
        choices = catalog['footer_backgrounds']
        self.assertEqual(choices, sorted(choices))
        self.assertEqual(choices[0], 'footer-backgrounds/' + self.name)
        self.assertEqual((output / choices[0]).read_bytes(), self.asset.read_bytes())
        normal = next(i for i in Page((output / 'index.html').read_text()).images if 'data-footer-background' in i)
        self.assertEqual(normal['src'], quote(choices[0], safe='/'))
        self.assertEqual((normal['width'], normal['height']), ('1200', '400'))
        self.assertEqual(json.loads(normal['data-background-sizes'])[0], [1200, 400])
        self.assertEqual(json.loads(normal['data-backgrounds']), [quote(path, safe='/') for path in choices])
        self.assertFalse(any('navypattern' in choice for choice in choices))
